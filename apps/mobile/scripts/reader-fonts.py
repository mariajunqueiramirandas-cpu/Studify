"""Builds src/components/reader-fonts.ts: the faces the note reader's WebView uses, as base64 WOFF2 subsets.

The WebView cannot load the app's bundled fonts and must work offline, so the faces travel inline in the page's CSS.
Subsetting to Latin (with PT-BR diacritics), Greek and the symbols notes use keeps each face around 20-40 KB.

    pip install fonttools brotli
    python3 apps/mobile/scripts/reader-fonts.py   # from the repository root, after pnpm install
"""
import base64
import io
import pathlib

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[3]
FONTS = ROOT / 'node_modules' / '@expo-google-fonts'
OUT = ROOT / 'apps' / 'mobile' / 'src' / 'components' / 'reader-fonts.ts'

# export name -> (package, file); MarkdownView declares the @font-face weights and styles.
FACES = {
    'literata': ('literata', '400Regular/Literata_400Regular.ttf'),
    'literataItalic': ('literata', '400Regular_Italic/Literata_400Regular_Italic.ttf'),
    'literataBold': ('literata', '700Bold/Literata_700Bold.ttf'),
    'bricolage': ('bricolage-grotesque', '800ExtraBold/BricolageGrotesque_800ExtraBold.ttf'),
    'figtree': ('figtree', '400Regular/Figtree_400Regular.ttf'),
    'figtreeSemiBold': ('figtree', '600SemiBold/Figtree_600SemiBold.ttf'),
    'atkinson': ('atkinson-hyperlegible', '400Regular/AtkinsonHyperlegible_400Regular.ttf'),
    'atkinsonBold': ('atkinson-hyperlegible', '700Bold/AtkinsonHyperlegible_700Bold.ttf'),
}

UNICODES = (
    list(range(0x20, 0x7F))  # Basic Latin
    + list(range(0xA0, 0x180))  # Latin-1 Supplement, Latin Extended-A
    + list(range(0x370, 0x400))  # Greek
    + list(range(0x2010, 0x2070))  # punctuation, super/subscripts
    + list(range(0x2070, 0x20A0))
    + list(range(0x2190, 0x2200))  # arrows
    + list(range(0x2200, 0x2300))  # math operators
    + [0x20AC, 0x2122, 0x2116, 0x25CF, 0x25A0, 0x2713]
)


def subset_woff2(path: pathlib.Path) -> bytes:
    font = TTFont(path)
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['kern', 'liga', 'calt', 'onum', 'lnum', 'tnum', 'frac', 'sups', 'subs']
    options.name_IDs = []
    options.hinting = False
    sub = subset.Subsetter(options)
    sub.populate(unicodes=UNICODES)
    sub.subset(font)
    buf = io.BytesIO()
    font.flavor = 'woff2'
    font.save(buf)
    return buf.getvalue()


def main() -> None:
    lines = [
        '// Generated by apps/mobile/scripts/reader-fonts.py: do not edit by hand.',
        '// WOFF2 subsets of the reading faces for the note reader WebView (SIL Open Font License 1.1).',
        '',
        'export const READER_FONTS = {',
    ]
    for name, (pkg, file) in FACES.items():
        data = subset_woff2(FONTS / pkg / file)
        print(f'{name}: {len(data) // 1024} KB')
        lines.append(f"  {name}: '{base64.b64encode(data).decode()}',")
    lines += ['} as const;', '']
    OUT.write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
