// Inlines drizzle-kit output into a self-contained `migrations.js` for Metro.
// drizzle-kit's `driver: 'expo'` bundle imports `.sql`/`.json` files, which Metro only loads with
// an `assetExts` change. This script embeds them as strings instead.
// Usage (from apps/mobile): npx drizzle-kit generate --name <slug> && node src/db/migrations/bundle.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = dirname(fileURLToPath(import.meta.url));
const journal = JSON.parse(readFileSync(join(dir, 'meta/_journal.json'), 'utf8'));

const entries = journal.entries.map((entry) => {
  const sql = readFileSync(join(dir, `${entry.tag}.sql`), 'utf8');
  return { key: `m${String(entry.idx).padStart(4, '0')}`, sql };
});

const lines = [
  '// GENERATED by src/db/migrations/bundle.mjs from drizzle-kit output. Do not edit by hand.',
  `const journal = ${JSON.stringify(journal, null, 2)};`,
  'const migrations = {',
  ...entries.map((e) => `  ${e.key}: ${JSON.stringify(e.sql)},`),
  '};',
  'export default { journal, migrations };',
  '',
];
writeFileSync(join(dir, 'migrations.js'), lines.join('\n'));
console.log(`Bundled ${entries.length} migration(s) into migrations.js`);
