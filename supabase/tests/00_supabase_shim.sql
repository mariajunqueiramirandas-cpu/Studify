-- Local stand-in for the Supabase platform surface that the migrations rely on.
-- NOT a migration: applied only by supabase/tests/run.sh, before supabase/migrations. Idempotent.
-- Covers: API roles, auth.users + auth.uid()/role()/jwt(), storage tables + foldername(),
-- the supabase_realtime publication, Supabase's default privileges on public, and pgcrypto
-- preinstalled in the extensions schema (so the migrations' `create extension` is a no-op, as there).

do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then
    create role anon nologin noinherit;
  end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then
    create role authenticated nologin noinherit;
  end if;
  if not exists (select 1 from pg_roles where rolname = 'service_role') then
    create role service_role nologin noinherit bypassrls;
  end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticator') then
    create role authenticator login noinherit;
  end if;
end $$;

alter role service_role bypassrls;
grant anon, authenticated, service_role to authenticator;

create schema if not exists auth;
create schema if not exists storage;
create schema if not exists extensions;
create extension if not exists pgcrypto with schema extensions;
grant usage on schema extensions to anon, authenticated, service_role;

grant usage on schema public to anon, authenticated, service_role;
grant usage on schema auth to anon, authenticated, service_role;
grant usage on schema storage to anon, authenticated, service_role;

-- Supabase grants the API roles full table/function privileges in public; RLS does the filtering.
alter default privileges in schema public grant all on tables to anon, authenticated, service_role;
alter default privileges in schema public grant all on sequences to anon, authenticated, service_role;
alter default privileges in schema public grant execute on functions to anon, authenticated, service_role;

-- auth.users (only the columns the app and tests use)
create table if not exists auth.users (
  id         uuid primary key,
  email      text unique,
  created_at timestamptz not null default now()
);
revoke all on auth.users from anon, authenticated, service_role;

-- Same resolution order as Supabase: request.jwt.claim.sub, then the claims JSON.
create or replace function auth.jwt() returns jsonb
language sql stable as $$
  select nullif(coalesce(nullif(current_setting('request.jwt.claim', true), ''),
                         nullif(current_setting('request.jwt.claims', true), '')), '')::jsonb
$$;

create or replace function auth.uid() returns uuid
language sql stable as $$
  select coalesce(nullif(current_setting('request.jwt.claim.sub', true), ''),
                  auth.jwt() ->> 'sub')::uuid
$$;

create or replace function auth.role() returns text
language sql stable as $$
  select coalesce(nullif(current_setting('request.jwt.claim.role', true), ''),
                  auth.jwt() ->> 'role')::text
$$;

-- storage: buckets/objects and foldername() as in Supabase (path segments, last one removed)
create table if not exists storage.buckets (
  id                 text primary key,
  name               text not null unique,
  owner              uuid,
  public             boolean not null default false,
  file_size_limit    bigint,
  allowed_mime_types text[],
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);

create table if not exists storage.objects (
  id               uuid primary key default gen_random_uuid(),
  bucket_id        text references storage.buckets(id),
  name             text,
  owner            uuid,
  metadata         jsonb,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  last_accessed_at timestamptz not null default now(),
  unique (bucket_id, name)
);

alter table storage.buckets enable row level security;
alter table storage.objects enable row level security;
grant all on storage.buckets, storage.objects to anon, authenticated, service_role;

create or replace function storage.foldername(name text) returns text[]
language sql immutable as $$
  select coalesce((string_to_array(name, '/'))[1 : array_length(string_to_array(name, '/'), 1) - 1], '{}'::text[])
$$;

-- Realtime publication (tables are added by the migrations).
do $$
begin
  if not exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    create publication supabase_realtime;
  end if;
end $$;

-- Realtime authorization (data-model.md §8.2): private channels are checked by policies on
-- realtime.messages, and realtime.topic() returns the channel being joined or sent to.
create schema if not exists realtime;
grant usage on schema realtime to anon, authenticated, service_role;

create table if not exists realtime.messages (
  id          bigint generated by default as identity primary key,
  topic       text not null,
  extension   text not null,
  event       text,
  payload     jsonb,
  private     boolean not null default false,
  inserted_at timestamp not null default now(),
  updated_at  timestamp not null default now()
);
alter table realtime.messages enable row level security;
grant select, insert on realtime.messages to anon, authenticated, service_role;

create or replace function realtime.topic() returns text
language sql stable as $$
  select nullif(current_setting('realtime.topic', true), '')::text
$$;
